/**
 * The briefs the composer offers, and the six it puts on the chip row.
 *
 * 350 lines of prose that lived in PromptTemplates.tsx, where the component
 * that renders them is sixty lines at the bottom. Data filed with the thing
 * that draws it — the same shape as the design specifications that used to sit
 * in graph.ts.
 *
 * Why these are briefs rather than page descriptions is explained below, and it
 * is the part worth reading before editing one: the pipeline is built around a
 * design phase that decides screens and an interaction inventory, and a
 * one-sentence brief leaves most of that machinery with nothing to do.
 */
export interface Template {
  id: string;
  category: string;
  label: string;
  /** One line under the label, so the card is readable without the whole brief. */
  summary: string;
  prompt: string;
}

/**
 * Briefs, not page descriptions.
 *
 * These used to be one sentence each — "ECサイトのトップページ。ヒーローバナー、
 * 商品カード4つ、カテゴリナビゲーション、フッター付き。" — and that is a description
 * of a picture. The pipeline is built around something else entirely: a design
 * phase that decides screens and information architecture, an interaction
 * designer that enumerates every control and the state it writes, and a build
 * that implements one screen per call against that inventory. Handed a single
 * static page, most of that machinery has nothing to do, and the result is the
 * flat output it produces from a flat brief.
 *
 * So each template now names what the design phase actually needs:
 *
 *   - the domain, concretely, because the visual language follows from it
 *   - four to six screens and what each is for
 *   - the state the app holds and the actions that write it
 *   - the shape of the data, so the seed records are plausible
 *   - which screen reaches which, so nothing ends up unreachable
 *
 * And then the three the pipeline was spending its repair passes guessing:
 *
 *   - 状態 — what each screen looks like with nothing in it, mid-flight, and
 *     after a failure. A generated screen is nearly always drawn full of data,
 *     because that is the only state a brief describes; the empty one is the
 *     state a real user meets first.
 *   - 画面が狭いとき — what folds. Not breakpoints, which are the designer's:
 *     which content survives the fold is the product's.
 *   - 外せない点 — the two or three rules that make this product not the
 *     generic one in its category. This is the section that decides whether the
 *     output could be any CRM or is this CRM.
 *
 * Written per template rather than appended to all sixteen. A block identical
 * in every brief is a statement about generation, not about this product, and
 * belongs in the build prompt where it applies to typed requests too.
 *
 * They are long on purpose. A template is the one place a user is shown what a
 * brief for this product looks like, and a thin example teaches a thin brief.
 *
 * Revised 2026-09-23, and the length is spent differently rather than cut:
 *
 *   - ナビゲーション — which screens the menu holds, and how the rest are
 *     reached. The storefront built from this file listed 商品詳細・
 *     チェックアウト・注文完了 in its menu and took payment for an empty cart;
 *     a detail, a checkout or a completion screen needs something first, and
 *     the brief now says what and what it shows without it.
 *   - No 読み込み中. The data is static and there is no loading; asking for a
 *     skeleton makes the build fake a delay, and the browser walk photographs
 *     the skeleton instead of the screen the critic is meant to judge.
 *   - No "Tab で辿れる". Keyboard reach is added deterministically to every
 *     build (tools/keyboard-reach.ts); a brief repeating it is paid for in
 *     every call the brief is sent to. Keys that are this product's own — the
 *     calendar's arrows, the size picker's — stay.
 */
